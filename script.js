/* ================= TABS: game / AI ================= */
const tabs = [...document.querySelectorAll('[role="tab"]')];

function selectTab(tab) {
    tabs.forEach(tb => {
        const on = tb === tab;
        tb.classList.toggle("active", on);
        tb.setAttribute("aria-selected", String(on));
        tb.tabIndex = on ? 0 : -1;
        document.getElementById(tb.getAttribute("aria-controls")).hidden = !on;
    });
}

// Link #projects-ai mở thẳng tab dự án AI.
if (location.hash === "#projects-ai") {
    selectTab(document.getElementById("tab-ai"));
    document.getElementById("projects").scrollIntoView();
}

tabs.forEach((tab, i) => {
    tab.addEventListener("click", () => selectTab(tab));
    tab.addEventListener("keydown", (e) => {
        if (e.key !== "ArrowRight" && e.key !== "ArrowLeft") return;
        const next = tabs[(i + (e.key === "ArrowRight" ? 1 : tabs.length - 1)) % tabs.length];
        selectTab(next);
        next.focus();
    });
});

/* ================= MODAL: chi tiết game ================= */
const overlay = document.getElementById("modal-overlay");
const modalContent = document.getElementById("modal-content");
let sliderAutoplay = null;
let lastFocusedElement = null;

function modalImageTag(src, title, idx) {
    return `<img class="media media-shot" src="${src}" alt="${title} screenshot ${idx + 1}" loading="lazy">`;
}

function modalMediaHtml(p) {
    if (p.video) {
        return `<video class="media media-video" controls autoplay muted loop playsinline aria-label="${p.title} trailer"><source src="${p.video}" type="video/mp4"></video>`;
    }
    const imgs = p.screenshots || [];
    if (imgs.length === 1) return modalImageTag(imgs[0], p.title, 0);
    if (imgs.length) {
        return `<div class="media-slider" data-slider>
          <div class="slider-viewport">${imgs.map((src, i) => modalImageTag(src, p.title, i)).join("")}</div>
          <button class="slider-btn slider-prev" type="button" aria-label="Previous screenshot">‹</button>
          <button class="slider-btn slider-next" type="button" aria-label="Next screenshot">›</button>
          <div class="slider-dots">${imgs.map((_, i) => `<button type="button" class="slider-dot${i === 0 ? " active" : ""}" aria-label="Show screenshot ${i + 1}"></button>`).join("")}</div>
        </div>`;
    }
    return `<div class="media media-empty"></div>`;
}

function openModal(p) {
    lastFocusedElement = document.activeElement;
    const vi = currentLang === "vi";
    const keys = Object.keys(p.links || {});
    modalContent.innerHTML = `
      <button class="modal-close" id="modal-close-btn" aria-label="Close">✕</button>
      ${modalMediaHtml(p)}
      <h2 id="modal-title">${p.title}</h2>
      <p class="meta">${t(p.genre)}. ${p.studio}, ${t(p.role)}.</p>
      <section><h3>${vi ? "Giới thiệu game" : "About the game"}</h3><div>${t(p.overview)}</div></section>
      <section><h3>${vi ? "Phần mình đóng góp" : "My contributions"}</h3><div>${t(p.desc)}</div></section>
      ${keys.length ? `<div class="plat-links">${keys.map((k, i) => linkHtml(p, k, i === 0 ? "btn btn-accent" : "btn btn-quiet")).join("")}</div>` : ""}
    `;
    overlay.classList.add("open");
    overlay.setAttribute("aria-hidden", "false");
    document.body.classList.add("modal-open");
    overlay.scrollTop = 0;
    document.getElementById("modal-close-btn").addEventListener("click", closeModal);
    document.getElementById("modal-close-btn").focus();

    const slider = modalContent.querySelector("[data-slider]");
    if (slider) {
        const slides = [...slider.querySelectorAll(".media-shot")];
        const dots = [...slider.querySelectorAll(".slider-dot")];
        let current = 0;
        const showSlide = (index) => {
            current = (index + slides.length) % slides.length;
            slides.forEach((slide, i) => slide.classList.toggle("active", i === current));
            dots.forEach((dot, i) => dot.classList.toggle("active", i === current));
        };
        const restart = () => {
            clearInterval(sliderAutoplay);
            if (!reduceMotion) sliderAutoplay = setInterval(() => showSlide(current + 1), 4000);
        };
        slider.querySelector(".slider-prev").addEventListener("click", () => { showSlide(current - 1); restart(); });
        slider.querySelector(".slider-next").addEventListener("click", () => { showSlide(current + 1); restart(); });
        dots.forEach((dot, i) => dot.addEventListener("click", () => { showSlide(i); restart(); }));
        showSlide(0);
        restart();
        slider.addEventListener("mouseenter", () => clearInterval(sliderAutoplay));
        slider.addEventListener("mouseleave", restart);
    }
}

function closeModal() {
    overlay.classList.remove("open");
    overlay.setAttribute("aria-hidden", "true");
    document.body.classList.remove("modal-open");
    clearInterval(sliderAutoplay);
    sliderAutoplay = null;
    modalContent.innerHTML = "";
    if (lastFocusedElement?.isConnected) lastFocusedElement.focus();
    lastFocusedElement = null;
}

overlay.addEventListener("click", (e) => { if (e.target === overlay) closeModal(); });
document.addEventListener("keydown", (e) => {
    if (!overlay.classList.contains("open")) return;
    if (e.key === "Escape") {
        closeModal();
        return;
    }
    if (e.key === "Tab") {
        const focusable = [...modalContent.querySelectorAll('button, a[href], video[controls]')];
        const first = focusable[0];
        const last = focusable[focusable.length - 1];
        if (e.shiftKey && document.activeElement === first) {
            e.preventDefault();
            last.focus();
        } else if (!e.shiftKey && document.activeElement === last) {
            e.preventDefault();
            first.focus();
        }
    }
});

/* ================= MOTION ================= */
const reduceMotion = matchMedia("(prefers-reduced-motion: reduce)").matches;

// Hiện từng phần của section khi cuộn tới (heading → text → hình).
const revealObserver = "IntersectionObserver" in window
    ? new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                entry.target.classList.add("in");
                revealObserver.unobserve(entry.target);
            }
        });
    }, { rootMargin: "0px 0px -6% 0px" })
    : null;

function observeReveals() {
    document.querySelectorAll("[data-reveal]:not(.in)").forEach(el => {
        if (revealObserver && !reduceMotion) revealObserver.observe(el);
        else el.classList.add("in");
    });
}

/* ================= NAV: nền khi cuộn + highlight mục hiện tại ================= */
const nav = document.getElementById("nav");
window.addEventListener("scroll", () => nav.classList.toggle("scrolled", window.scrollY > 8), { passive: true });

const navLinks = [...document.querySelectorAll(".links a")];
const sectionObserver = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
        if (!entry.isIntersecting) return;
        navLinks.forEach(a => a.classList.toggle("active", a.getAttribute("href") === "#" + entry.target.id));
    });
}, { rootMargin: "-45% 0px -50% 0px" });
document.querySelectorAll("main section[id]").forEach(sec => sectionObserver.observe(sec));

renderAll();
observeReveals();
