/* ================= HELPERS: nhãn & icon cho từng loại link ================= */
const STORE_LABELS = {
    googlePlay: "Google Play",
    appStore: "App Store",
    steam: "Steam",
    website: "Website",
    devlog1: "Devlog 1",
    devlog2: "Devlog 2",
    devlog3: "Devlog 3"
};

// Sinh danh sách "chip" nền tảng hiển thị trên card (chỉ hiện platform có link thật)
function platformChipsHtml(p) {
    return Object.keys(p.links)
        .map((key) => `<span class="plat">${STORE_LABELS[key] || key}</span>`)
        .join("");
}

// Sinh danh sách nút bấm mở store/website trong modal (chỉ hiện platform có link thật)
function platformButtonsHtml(p) {
    const keys = Object.keys(p.links);
    return keys
        .map((key, i) => {
            const cls = i === 0 ? "btn btn-primary" : "btn btn-ghost";
            return `<a class="${cls}" href="${p.links[key]}" target="_blank" rel="noopener">${STORE_LABELS[key] || key} →</a>`;
        })
        .join("");
}

function projectCoverSrc(p) {
    return p.thumbnail || p.media || (p.screenshots && p.screenshots[0]) || null;
}

function projectModalImages(p) {
    if (p.screenshots && p.screenshots.length) return p.screenshots;
    const single = p.media || p.thumbnail;
    return single ? [single] : [];
}

// Ảnh thumbnail card (fallback = placeholder)
function cardThumbHtml(p) {
    const src = projectCoverSrc(p);
    if (src) {
        const fit = p.thumbnailFit || "cover";
        return `<img class="card-thumb-image card-thumb-image-${fit}" src="${src}" alt="${p.title}" loading="lazy">`;
    }
    if (p.assetPlaceholder) {
        return `<div class="asset-placeholder" aria-label="Coming asset"><span>COMING ASSET</span></div>`;
    }
    return `<div class="play-ic" aria-hidden="true">
    <svg width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.6"><rect x="3" y="5" width="18" height="14" rx="2"/><circle cx="8.5" cy="10" r="1.5" fill="currentColor" stroke="none"/><path d="M21 16l-5-4-4 3-3-2-6 5"/></svg>
  </div>`;
}

function modalImageTag(src, title, idx) {
    const alt = idx > 0 ? `${title} screenshot ${idx + 1}` : `${title} screenshot`;
    return `<img class="media media-shot" src="${src}" alt="${alt}" loading="lazy">`;
}

function modalVideoTag(src, title) {
    return `<video class="media media-video" controls autoplay muted loop playsinline aria-label="${title} trailer"><source src="${src}" type="video/mp4">Your browser does not support video playback.</video>`;
}

// Modal: chỉ ảnh screenshot (không video)
function modalMediaHtml(p) {
    if (p.video) return modalVideoTag(p.video, p.title);
    const imgs = projectModalImages(p);
    if (imgs.length) {
        if (imgs.length === 1) return modalImageTag(imgs[0], p.title, 0);
        return `<div class="media-slider" data-slider>
          <div class="slider-viewport">${imgs.map((src, i) => modalImageTag(src, p.title, i)).join("")}</div>
          <button class="slider-btn slider-prev" type="button" aria-label="Previous screenshot">‹</button>
          <button class="slider-btn slider-next" type="button" aria-label="Next screenshot">›</button>
          <div class="slider-dots" role="tablist">${imgs.map((_, i) => `<button type="button" class="slider-dot${i === 0 ? " active" : ""}" data-slide="${i}" aria-label="Show screenshot ${i + 1}"></button>`).join("")}</div>
        </div>`;
    }
    if (p.assetPlaceholder) {
        return `<div class="media media-empty asset-coming" aria-label="Coming asset">COMING ASSET</div>`;
    }
    const hint = currentLang === "vi"
        ? `Chưa có ảnh — thêm thumbnail, media hoặc screenshots[] cho "${p.title}" (vd. images/${p.id}.jpg)`
        : `No screenshots yet — set thumbnail, media, or screenshots[] for "${p.title}" (e.g. images/${p.id}.jpg)`;
    return `<div class="media media-empty">${hint}</div>`;
}

