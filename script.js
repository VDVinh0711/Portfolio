/* ================= MODAL: chi tiết game ================= */
const overlay = document.getElementById("modal-overlay");
const modalContent = document.getElementById("modal-content");
let sliderAutoplay = null;
let lastFocusedElement = null;

function openModal(p) {
    lastFocusedElement = document.activeElement;
    const overviewHtml = p.overview?.[currentLang]
        ? `<section class="project-overview"><h3>${currentLang === "vi" ? "Giới thiệu game" : "About the game"}</h3><div>${p.overview[currentLang]}</div></section>`
        : "";
    const contributionsHtml = p.desc?.[currentLang]
        ? `<section class="project-contributions"><h3>${currentLang === "vi" ? "Phần mình đóng góp" : "My contributions"}</h3><div class="desc">${p.desc[currentLang]}</div></section>`
        : "";
    const linksHtml = Object.keys(p.links || {}).length
        ? `<div class="plat-links">${platformButtonsHtml(p)}</div>`
        : "";
    modalContent.innerHTML = `
      <button class="modal-close" id="modal-close-btn" aria-label="Close">✕</button>
      ${modalMediaHtml(p)}
      <h2 id="modal-title">${p.title}</h2>
      <div class="tag-row">
<span class="chip">${p.genre[currentLang]}</span>
<span class="chip">${p.studio}</span>
<span class="chip">${p.role[currentLang]}</span>
      </div>
      ${overviewHtml}
      ${contributionsHtml}
      ${linksHtml}
    `;
    overlay.classList.add("open");
    overlay.setAttribute("aria-hidden", "false");
    document.body.classList.add("modal-open");
    document.getElementById("modal-close-btn").addEventListener("click", closeModal);
    document.getElementById("modal-close-btn").focus();
    const slider = modalContent.querySelector("[data-slider]");
    if (slider) {
        const slides = [...slider.querySelectorAll(".media-shot")];
        const dots = [...slider.querySelectorAll(".slider-dot")];
        let current = 0;
        const showSlide = (index) => {
            current = (index + slides.length) % slides.length;
            slides.forEach((slide, i) => {
                const isCurrent = i === current;
                // Set both the class and inline display so the transition is
                // reliable even when another stylesheet overrides the slider CSS.
                slide.classList.toggle("active", isCurrent);
                slide.style.display = isCurrent ? "block" : "none";
            });
            dots.forEach((dot, i) => dot.classList.toggle("active", i === current));
        };
        slider.querySelector(".slider-prev").addEventListener("click", (event) => {
            event.preventDefault();
            event.stopPropagation();
            showSlide(current - 1);
        });
        slider.querySelector(".slider-next").addEventListener("click", (event) => {
            event.preventDefault();
            event.stopPropagation();
            showSlide(current + 1);
        });
        dots.forEach((dot, i) => dot.addEventListener("click", (event) => {
            event.preventDefault();
            event.stopPropagation();
            showSlide(i);
        }));
        showSlide(0);

        // Tự động chuyển ảnh theo đúng thứ tự trong screenshots[] mỗi 4 giây.
        sliderAutoplay = setInterval(() => showSlide(current + 1), 4000);
        slider.addEventListener("mouseenter", () => clearInterval(sliderAutoplay), { once: false });
        slider.addEventListener("mouseleave", () => {
            clearInterval(sliderAutoplay);
            sliderAutoplay = setInterval(() => showSlide(current + 1), 4000);
        });
    }
}
function closeModal() {
    overlay.classList.remove("open");
    overlay.setAttribute("aria-hidden", "true");
    document.body.classList.remove("modal-open");
    clearInterval(sliderAutoplay);
    sliderAutoplay = null;
    if (lastFocusedElement?.isConnected) lastFocusedElement.focus();
    lastFocusedElement = null;
}
overlay.addEventListener("click", (e) => { if (e.target === overlay) closeModal(); });
document.addEventListener("keydown", (e) => {
    if (!overlay.classList.contains("open")) return;
    if (e.key === "Escape") {
        closeModal();
        return;
    }
    if (e.key === "Tab") {
        const focusable = [...modalContent.querySelectorAll('button, a[href], video[controls]')];
        const first = focusable[0];
        const last = focusable[focusable.length - 1];
        if (e.shiftKey && document.activeElement === first) {
            e.preventDefault();
            last.focus();
        } else if (!e.shiftKey && document.activeElement === last) {
            e.preventDefault();
            first.focus();
        }
    }
});
